"""`sunaba rebuild` keeps local edits: `.new` proposals, the settings
merge, the USER region of agent files, and the `.sunaba/generated.json`
record that tells the user's edits from sunaba's own output."""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

from sunaba_cli import regen
from sunaba_cli.cli import _build_config_files

MANIFEST = regen.MANIFEST_PATH
SETTINGS = ".claude/settings.json"


def _run(args: list[str], cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, "-m", "sunaba_cli.cli", *args], cwd=str(cwd),
                          env=os.environ.copy(), capture_output=True, text=True)


@pytest.fixture
def workspace(tmp_path, monkeypatch) -> Path:
    home = tmp_path / "home"
    home.mkdir()
    monkeypatch.setenv("HOME", str(home))
    ws = tmp_path / "ws"
    ws.mkdir()
    return ws


def _new(ws: Path, name: str, *stacks: str) -> Path:
    args = ["new", name, "--no-prompt"]
    for s in stacks:
        args += ["--stack", s]
    r = _run(args, ws)
    assert r.returncode == 0, r.stderr
    return ws / name


def _rebuild(ws: Path, name: str, *extra: str) -> subprocess.CompletedProcess:
    r = _run(["rebuild", name, *extra], ws)
    assert r.returncode == 0, f"stderr: {r.stderr}\nstdout: {r.stdout}"
    return r


# --- the record --------------------------------------------------------------


def test_new_records_what_it_generated(workspace):
    project = _new(workspace, "rec", "python", "harness")
    files = json.loads((project / MANIFEST).read_text())["files"]
    generated = _build_config_files("rec", ["python", "harness"])
    assert set(files) == set(generated)
    for rel, entry in files.items():
        assert entry["sha256"] == regen.fingerprint((project / rel).read_text()), rel
    # The settings merge needs the generated JSON as its base.
    assert json.loads(files[SETTINGS]["base"]) == json.loads(generated[SETTINGS])


# --- untouched files update, edited files get proposals ----------------------


def test_untouched_files_update_in_place(workspace):
    project = _new(workspace, "up", "python")
    _rebuild(workspace, "up", "--add", "aws", "--yes")
    dc = (project / ".devcontainer/devcontainer.json").read_text()
    assert "aws" in dc.lower()
    assert not list(project.rglob("*.new"))


def test_edited_file_is_kept_and_regenerated_beside_it(workspace):
    project = _new(workspace, "ed", "python")
    dc = project / ".devcontainer/devcontainer.json"
    mine = dc.read_text().replace('"name": "sunaba-ed"', '"name": "my-team-box"')
    dc.write_text(mine)

    r = _rebuild(workspace, "ed", "--add", "aws", "--yes")

    assert dc.read_text() == mine
    proposal = project / ".devcontainer/devcontainer.json.new"
    assert "aws" in proposal.read_text().lower()
    assert "edited locally" in r.stdout
    assert "diff .devcontainer/devcontainer.json .devcontainer/devcontainer.json.new" in r.stdout


def test_proposal_is_not_rewritten_when_up_to_date(workspace):
    project = _new(workspace, "idem", "python")
    dc = project / ".devcontainer/devcontainer.json"
    dc.write_text(dc.read_text() + "\n")
    _rebuild(workspace, "idem", "--add", "aws", "--yes")
    r = _rebuild(workspace, "idem", "--yes")
    assert "is up to date" in r.stdout
    assert "Nothing to change." in r.stdout


def test_overwrite_replaces_edited_files(workspace):
    project = _new(workspace, "ow", "python")
    dc = project / ".devcontainer/devcontainer.json"
    dc.write_text(dc.read_text().replace('"name": "sunaba-ow"', '"name": "mine"'))
    _rebuild(workspace, "ow", "--add", "aws", "--yes", "--overwrite")
    assert '"name": "sunaba-ow"' in dc.read_text()
    assert not (project / ".devcontainer/devcontainer.json.new").exists()


def test_dry_run_writes_nothing(workspace):
    project = _new(workspace, "dry", "python")
    dc = project / ".devcontainer/devcontainer.json"
    dc.write_text(dc.read_text().replace('"name": "sunaba-dry"', '"name": "mine"'))
    before = (project / MANIFEST).read_text()
    r = _rebuild(workspace, "dry", "--add", "aws", "--dry-run")
    assert "(propose: edited locally" in r.stdout
    assert not list(project.rglob("*.new"))
    assert (project / MANIFEST).read_text() == before


def test_project_without_a_record_gets_proposals(workspace):
    """Before the record existed, sunaba cannot tell an outdated file from an
    edited one, so it keeps every file that differs."""
    project = _new(workspace, "leg", "python")
    (project / MANIFEST).unlink()
    r = _rebuild(workspace, "leg", "--add", "aws", "--yes")
    assert "not recorded as generated by sunaba" in r.stdout
    assert "--overwrite" in r.stdout
    assert (project / ".devcontainer/devcontainer.json.new").is_file()
    # The record is written, so the next rebuild can update in place.
    assert (project / MANIFEST).is_file()


def test_edited_proposal_is_left_alone(workspace):
    """A `.new` the user has started merging in is theirs, not sunaba's."""
    project = _new(workspace, "pe", "python")
    dc = project / ".devcontainer/devcontainer.json"
    dc.write_text(dc.read_text() + "\n")
    _rebuild(workspace, "pe", "--add", "aws", "--yes")
    proposal = project / ".devcontainer/devcontainer.json.new"
    proposal.write_text(proposal.read_text() + "// half merged\n")

    r = _rebuild(workspace, "pe", "--add", "gcp", "--yes")

    assert proposal.read_text().endswith("// half merged\n")
    assert "has your edits" in r.stdout


def test_stale_proposal_sunaba_wrote_is_refreshed(workspace):
    project = _new(workspace, "ps", "python")
    dc = project / ".devcontainer/devcontainer.json"
    dc.write_text(dc.read_text() + "\n")
