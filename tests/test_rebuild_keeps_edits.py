# --- agent files: the USER region is the user's ------------------------------


def test_user_region_of_agents_md_survives_rebuild(workspace):
    """Regression: rebuild used to regenerate AGENTS.md without the USER region."""
    project = _new(workspace, "usr", "python")
    agents = project / "AGENTS.md"
    text = agents.read_text()
    assert regen.USER_END in text
    agents.write_text(text.replace(regen.USER_END, "MY TEAM RULE\n" + regen.USER_END))

    _rebuild(workspace, "usr", "--add", "secrets", "--yes")

    after = agents.read_text()
    assert "MY TEAM RULE" in after
    assert "secrets" in after.lower()  # the stacks section did update
    assert not (project / "AGENTS.md.new").exists()


def test_user_region_is_not_dropped_by_a_template_without_one(workspace):
    """The harness AGENTS.md has no USER markers. The fingerprint ignores the
    region, so the file looks untouched; updating it would drop the region."""
    project = _new(workspace, "nr", "python")
    agents = project / "AGENTS.md"
    text = agents.read_text()
    agents.write_text(text.replace(regen.USER_END, "MY TEAM RULE\n" + regen.USER_END))
    generated = _build_config_files("nr", ["python", "harness"])["AGENTS.md"]
    assert regen.USER_START not in generated  # the premise of this test

    r = _rebuild(workspace, "nr", "--add", "harness", "--yes")

    assert "MY TEAM RULE" in agents.read_text()
    assert (project / "AGENTS.md.new").is_file()
    assert "no SUNABA USER region" in r.stdout


# --- .claude/settings.json ---------------------------------------------------


def test_settings_merge_adds_new_entries_and_keeps_removals(workspace):
    project = _new(workspace, "set", "harness")
    settings_path = project / SETTINGS
    user = json.loads(settings_path.read_text())
    user["permissions"]["allow"].append("Bash(make test:*)")      # user addition
    user["permissions"]["deny"].remove("Bash(sudo:*)")            # user removal
    user["permissions"]["deny"].remove("Bash(git reset --hard:*)")
    settings_path.write_text(json.dumps(user, indent=2) + "\n")

    # Pretend the previous sunaba did not generate the reset rule, so the
    # current template introduces it.
    manifest = json.loads((project / MANIFEST).read_text())
    base = json.loads(manifest["files"][SETTINGS]["base"])
    base["permissions"]["deny"].remove("Bash(git reset --hard:*)")
    manifest["files"][SETTINGS]["base"] = json.dumps(base)
    (project / MANIFEST).write_text(json.dumps(manifest))

    r = _rebuild(workspace, "set", "--yes")

    merged = json.loads(settings_path.read_text())
    assert "Bash(make test:*)" in merged["permissions"]["allow"]
    assert "Bash(git reset --hard:*)" in merged["permissions"]["deny"]  # new in template
    assert "Bash(sudo:*)" not in merged["permissions"]["deny"]          # removed by user
    assert "added permissions.deny: Bash(git reset --hard:*)" in r.stdout
    assert not (project / f"{SETTINGS}.new").exists()


def test_proposed_settings_keep_the_old_base(workspace):
    """While settings are proposed, not merged, the record keeps the old
    base; otherwise the next rebuild would count what was proposed as known
    and never add it."""
    project = _new(workspace, "pb", "harness")
    manifest = json.loads((project / MANIFEST).read_text())
    base = json.loads(manifest["files"][SETTINGS]["base"])
    base["permissions"]["deny"].remove("Bash(git reset --hard:*)")
    manifest["files"][SETTINGS]["base"] = json.dumps(base)
    (project / MANIFEST).write_text(json.dumps(manifest))
    good = json.loads((project / SETTINGS).read_text())
    good["permissions"]["deny"].remove("Bash(git reset --hard:*)")  # as the old sunaba wrote it
    (project / SETTINGS).write_text("{ broken")

    _rebuild(workspace, "pb", "--yes")             # proposes .new
    (project / SETTINGS).write_text(json.dumps(good))  # user repairs their file
    _rebuild(workspace, "pb", "--yes")

    merged = json.loads((project / SETTINGS).read_text())
    assert "Bash(git reset --hard:*)" in merged["permissions"]["deny"]


def test_unparseable_settings_get_a_proposal(workspace):
    project = _new(workspace, "bad", "harness")
    (project / SETTINGS).write_text("{ not json")
    _rebuild(workspace, "bad", "--yes")
    assert (project / SETTINGS).read_text() == "{ not json"
    json.loads((project / f"{SETTINGS}.new").read_text())


_TEMPLATE = {
    "permissions": {"allow": ["Bash(ls:*)", "Bash(new-allow:*)"], "deny": ["Bash(sudo:*)", "Bash(new-deny:*)"]},
    "hooks": {"PreToolUse": [{"matcher": "Bash", "hooks": [{"type": "command", "command": "guard"}]}]},
    "env": {"X": "1"},
}


def test_merge_without_base_never_widens_allow():
    user = {"permissions": {"allow": ["Bash(ls:*)"], "deny": []}}
    merged, added = regen.merge_claude_settings(user, _TEMPLATE, None)
    assert merged["permissions"]["allow"] == ["Bash(ls:*)"]
    assert merged["permissions"]["deny"] == ["Bash(sudo:*)", "Bash(new-deny:*)"]
    assert merged["hooks"]["PreToolUse"][0]["hooks"][0]["command"] == "guard"
    assert merged["env"] == {"X": "1"}
    assert not any(a.startswith("permissions.allow") for a in added)


def test_merge_with_base_adds_only_what_is_new():
    base = {"permissions": {"allow": ["Bash(ls:*)"], "deny": ["Bash(sudo:*)"]}, "env": {"X": "1"}}
    user = {"permissions": {"allow": [], "deny": []}}  # removed everything sunaba gave
    merged, added = regen.merge_claude_settings(user, _TEMPLATE, base)
    assert merged["permissions"]["allow"] == ["Bash(new-allow:*)"]
    assert merged["permissions"]["deny"] == ["Bash(new-deny:*)"]
    assert "env" not in merged  # removed by the user, not new
    assert "hooks.PreToolUse: guard" in added


def test_merge_is_idempotent_and_never_duplicates_hooks():
    once, _ = regen.merge_claude_settings({}, _TEMPLATE, None)
    twice, added = regen.merge_claude_settings(once, _TEMPLATE, None)
    assert twice == once and added == []
    assert len(twice["hooks"]["PreToolUse"]) == 1


def test_merge_with_a_damaged_base_never_widens_allow():
    user = {"permissions": {"allow": [], "deny": []}}
    merged, _ = regen.merge_claude_settings(user, _TEMPLATE, [])  # base was "[]"
    assert merged["permissions"]["allow"] == []


def test_merge_rejects_unexpected_shapes():
    with pytest.raises(ValueError):
        regen.merge_claude_settings({"permissions": {"deny": "Bash(sudo:*)"}}, _TEMPLATE, None)
    with pytest.raises(ValueError):
        regen.merge_claude_settings([], _TEMPLATE, None)


def test_fingerprint_ignores_only_the_user_region():
    a = f"head\n{regen.USER_START}\nmine\n{regen.USER_END}\ntail\n"
    b = f"head\n{regen.USER_START}\nsomething else\n{regen.USER_END}\ntail\n"
    c = a.replace("tail", "TAIL")
    assert regen.fingerprint(a) == regen.fingerprint(b)
    assert regen.fingerprint(a) != regen.fingerprint(c)
